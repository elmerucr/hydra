system_t::system_t()
{
    host = new host_t();
    nerve = new nerve_t(this);
    vdc = new vdc_t();

    r = 0;
    g = 0;
    b = 0;
}

system_t::~system_t()
{
    delete vdc;
    delete nerve;
    delete host;
}

void system_t::run()
{
    std::memcpy(vdc->ram.data() + 0x30000, swordmaster, sizeof(swordmaster));

    sprite_t hero_girl = {
        .gfx_addr = 0x30200,
        .sprite_w = 10,
        .sprite_h = 31,
        .sprite_id = 0
    };
    std::memcpy(vdc->ram.data() + hero_girl.gfx_addr, hero, sizeof(hero));

    sprite_t hydra = {
        .gfx_addr = 0x30400,
        .sprite_w = 20,
        .sprite_h = 20,
        .sprite_id = 0
    };
    std::memcpy(vdc->ram.data() + 0x30400, hydra_data, sizeof(hydra_data));

    typedef struct {
        int x;
        int y;
        int dx;
        int dy;
    } pos;

    rca_t rca;
    pos swordmaster_array[100];
    for (int i = 0; i < 100; i++) {
        swordmaster_array[i].x = rca.next_range(0, PIXELS_PER_SCANLINE - 16);
        swordmaster_array[i].y = rca.next_range(0, SCANLINES - 16);
        swordmaster_array[i].dx = rca.next_bit() ? 1 : -1;
        swordmaster_array[i].dy = rca.next_bit() ? 1 : -1;
    }

    for (int i = 0; i < 64; i++) {
        vdc->ram[0x000000 + i] = 0x18;
        vdc->ram[0x000040 + i] = 0x45;
    }
    vdc->ram[0x80] = 0;
    vdc->ram[0x81] = 1;
    vdc->ram[0x82] = 0;
    vdc->ram[0x83] = 1;
    vdc->ram[0x84] = 0;
    vdc->ram[0x85] = 1;
    vdc->ram[0x86] = 0;
    vdc->ram[0x87] = 1;
    vdc->ram[0x88] = 0;

    int16_t x = -48;
    int16_t y = -48;

    int16_t hero_x = 155;
    int16_t hero_y = 149;

    running = true;

    while (running) {
        if (host->events_process_events() == QUIT_EVENT) {
            running = false;
        }

        if (host->key_pressed(input_key_t::space)) {
            nerve->call_if_exists("on_space_pressed");
        }

        const bool upside_down = host->key_down(input_key_t::v);
        const bool hor_flip    = host->key_down(input_key_t::h);
        const bool hor_double  = host->key_down(input_key_t::x);
        const bool ver_double  = host->key_down(input_key_t::y);

        if (host->key_down(input_key_t::right)) hero_x++;
        if (host->key_down(input_key_t::left))  hero_x--;
        if (host->key_down(input_key_t::up))    hero_y--;
        if (host->key_down(input_key_t::down))  hero_y++;   
        
        vdc->clear(0x93);

        vdc->blit_tilemap(
            0x000080,
            136, y,
            3,3,
            hor_flip,
            upside_down,
            hor_double,
            ver_double,
            false,
            true,
            0x30000,
            16,16
        );
        vdc->blit_tilemap(
            0x000080,
            184, -y,
            3,3,
            hor_flip,
            upside_down,
            hor_double,
            ver_double,
            false,
            true,
            0x30000,
            16,16
        );
        x++; y++;
        if (x == 48) { x = -48; y = -48; }

        for (int i = 0; i < 100; i++) {
            vdc->blit_sprite(
                0x30000,
                swordmaster_array[i].x,
                swordmaster_array[i].y,
                16,
                16,
                swordmaster_array[i].dy == 1 ? 0 : 1,
                swordmaster_array[i].dx == 1 ? false : true,
                false,
                false,
                false
            );
            swordmaster_array[i].x += swordmaster_array[i].dx;
            if (swordmaster_array[i].x < 1 || swordmaster_array[i].x > (320 - 16)) swordmaster_array[i].dx = -swordmaster_array[i].dx;
            swordmaster_array[i].y += swordmaster_array[i].dy;
            if (swordmaster_array[i].y < 1 || swordmaster_array[i].y > (180 - 16)) swordmaster_array[i].dy = -swordmaster_array[i].dy;
        }
        
        // do checkerboard
        vdc->blit_tilemap(
            0x000080,
            43,
            43,
            3,
            3,
            false,
            false,
            false,
            false,
            false,
            false,
            0x000000,
            8,
            8
        );

        // hero girl
        hero_girl.dst_x = hero_x;
        hero_girl.dst_y = hero_y;
        hero_girl.flip_x = hor_flip;
        hero_girl.flip_y = upside_down;
        hero_girl.double_x = hor_double;
        hero_girl.double_y = ver_double;
        vdc->blit_sprite(&hero_girl);

        hydra.dst_x = 96;
        hydra.dst_y = 64;
        vdc->blit_sprite(&hydra);

        host->video_update_screen(vdc->buffer.data(), r, g, b);
    }
}
